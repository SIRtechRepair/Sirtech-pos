do $$
declare
  v_primera boolean;
  r record;
  v_id bigint;
  i int;
begin
  select not exists (select 1 from public.migraciones where clave = '08_servicios') into v_primera;
  if v_primera then
    -- 4.1 Preservar envío y repuestos que antes vivían a nivel de orden
    update public.ordenes o
       set envio_extra = o.envio,
           repuestos_extra = greatest(
             o.costo_repuestos - coalesce((
               select sum(i.costo_unitario * i.cantidad)
                 from public.orden_items i
                where i.orden_id = o.id and i.tipo = 'repuesto'
             ), 0), 0);

    -- 4.2 Renombrar y separar combos
    for r in
      select oi.id, oi.orden_id, m.nombres
        from public.orden_items oi
        join public._map_servicios m on m.raw = trim(oi.descripcion)
       where oi.tipo = 'servicio' and not oi.normalizado
    loop
      select id into v_id from public.servicios where nombre = r.nombres[1] limit 1;
      update public.orden_items
         set descripcion = r.nombres[1], servicio_id = v_id, normalizado = true
       where id = r.id;

      if array_length(r.nombres, 1) > 1 then
        for i in 2..array_length(r.nombres, 1) loop
          select id into v_id from public.servicios where nombre = r.nombres[i] limit 1;
          insert into public.orden_items
            (orden_id, tipo, descripcion, cantidad, costo_unitario,
             precio_unitario, servicio_id, envio, costo_repuestos, normalizado)
          values
            (r.orden_id, 'servicio', r.nombres[i], 1, 0,
             0, v_id, 0, 0, true);
        end loop;
      end if;
    end loop;

    update public.orden_items set normalizado = true where not normalizado;
    insert into public.migraciones (clave) values ('08_servicios') on conflict do nothing;
  end if;
end $$;

